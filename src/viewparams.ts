// Адрес страницы разбирается в одном месте (docs/specs/2026-10-05-4-glavnoe-okno.md,
// «Где снимать»): тема, состояние ленты и правая панель. Второго разбора адреса в коде
// нет — App берёт отсюда тему, фикстура — состояние ленты, ChatView — оверлей панели.
//
// В окне Tauri адреса нет: страница открыта как `tauri://localhost`, поэтому там тёмная
// тема и обычная лента, как раньше. Браузер отдаёт поиск в процентной кодировке, а
// URLSearchParams её разбирает сам — иначе `?тема=светлая` молча не сойдётся.

export type Theme = "dark" | "light";

/** Состояние экрана: лента пуста, с ошибкой, полна данных; выбрана папка проекта
 *  и справа дерево файлов; список плагинов — с ним или совсем пустой; каталог
 *  «Available» — то, что открывает «Browse plugins…»; одобрение вызова плагина —
 *  окно согласия вместо исполненной кнопки (`?состояние=`); панель сравнения
 *  моделей — открыта, раскрыта, из кэша, с ошибкой сети, в ожидании загрузки
 *  или с медленным ответом (задержка моста, как живой invoke). */
export type FeedState = "feed" | "empty" | "error" | "many" | "project" | "plugins" | "plugins-empty" | "approval" | "catalog" | "plugins-section" | "plugins-updates" | "настройки" | "настройки-модели" | "настройки-ключ" | "настройки-ключ-ошибка" | "настройки-плагины" | "настройки-данные" | "настройки-движок" | "статистика" | "статистика-пусто" | "разбор" | "маркдаун" | "прогресс" | "сравнение" | "сравнение-раскрыто" | "сравнение-кэш" | "сравнение-ошибка" | "сравнение-загрузка" | "сравнение-медленно";

export type ViewParams = {
  theme: Theme;
  feed: FeedState;
  /** Правая панель открыта оверлеем — кадр панели на любой ширине. */
  right: boolean;
  /** Меню «⋯» открыто — кадр меню без клика, как `правая=открыта` (спека §13). */
  menu: boolean;
  /** Обрыв потока по требованию сценария ленты (`?обрыв=1`). */
  breaks: boolean;
  /** Текст поиска по чатам — предзаполненное поле для кадров без кликов
   *  (спека сайдбара §13, `?поиск=<текст>`), как `меню=открыто`. */
  search: string;
  /** Меню «+» композера открыто на пустом чате (`?плюс=открыто`) — кадр героя
   *  без кликов (спека приветствия §11), как `меню=открыто`. */
  plus: boolean;
  /** Статистика не читается (`?статистика=нет`) — сводка расхода не приходит,
   *  счётчики приветственной сборки честно показывают прочерк (спека §9). */
  noStats: boolean;
};

const THEMES: Record<string, Theme> = { тёмная: "dark", темная: "dark", светлая: "light" };
const FEEDS: Record<string, FeedState> = {
  пусто: "empty",
  ошибка: "error",
  много: "many",
  проект: "project",
  плагины: "plugins",
  "плагины-пусто": "plugins-empty",
  "плагины-раздел": "plugins-section",
  "плагины-обновления": "plugins-updates",
  "настройки": "настройки",
  "настройки-модели": "настройки-модели",
  "настройки-ключ": "настройки-ключ",
  "настройки-ключ-ошибка": "настройки-ключ-ошибка",
  "настройки-плагины": "настройки-плагины",
  "настройки-данные": "настройки-данные",
  "настройки-движок": "настройки-движок",
  статистика: "статистика",
  "статистика-пусто": "статистика-пусто",
  одобрение: "approval",
  каталог: "catalog",
  разбор: "разбор",
  маркдаун: "маркдаун",
  прогресс: "прогресс",
  сравнение: "сравнение",
  "сравнение-раскрыто": "сравнение-раскрыто",
  "сравнение-кэш": "сравнение-кэш",
  "сравнение-ошибка": "сравнение-ошибка",
  "сравнение-загрузка": "сравнение-загрузка",
  "сравнение-медленно": "сравнение-медленно",
};

export function viewParams(search: string): ViewParams {
  const query = new URLSearchParams(search);
  return {
    theme: THEMES[query.get("тема") ?? ""] ?? "dark",
    feed: FEEDS[query.get("состояние") ?? ""] ?? "feed",
    right: query.get("правая") === "открыта",
    menu: query.get("меню") === "открыто",
    breaks: query.has("обрыв"),
    search: query.get("поиск") ?? "",
    plus: query.get("плюс") === "открыто",
    noStats: query.get("статистика") === "нет",
  };
}

/** Параметры текущей страницы: в окне Tauri поиск пуст, поэтому значения по умолчанию. */
export const params: ViewParams = viewParams(typeof location === "undefined" ? "" : location.search);