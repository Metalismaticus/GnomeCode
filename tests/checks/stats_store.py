"""Сбор расхода в stats.jsonl: cargo-тесты хранилища — одна строка на шаг
модели, повтор события не дублирует, обрыв потока и рестарт движка записанное
не теряют, испорченный файл — норма. Живая форма события v2.0.25 закреплена
кадрами зонда в src-tauri/tests/stats_store.rs (замер 2026-10-09).

Проверка идёт по тому же пути, что и продукт: cargo-тест на временных папках —
данные владельца не касаются (docs/TESTING.md, «Данные пользователя»).

Предел 300 с: сборка Rust считает минуты, «чинить» по таймауту нельзя
(docs/TESTING.md, «Ловушки стека»).
"""
import sys

from runner_lib import limit, report, run, tool_env, verdict, which

CARGO = [which("cargo"), "test", "--manifest-path", "src-tauri/Cargo.toml", "--test", "stats_store"]
OK = ("живые кадры v2.0.25 разбираются в типы и пишутся одной строкой; одна "
      "строка на шаг с длительностью и проектом; повтор шага не дублирует; "
      "обрыв и рестарт записанное хранят; шаг без начала пишет последнюю "
      "модель; чужие сессии и мусор в файле — норма; лента без новых строк")


def check():
    code, output = run(CARGO, limit("stats_store"), env=tool_env())
    return verdict(code, output, OK)


if __name__ == "__main__":
    sys.exit(report(check()))
