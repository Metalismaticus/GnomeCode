"""Сессия продолжается после перезапуска приложения: сохранённый идентификатор берётся из списка живых сессий движка.

Проверка идёт по тому же пути, что и продукт: живой движок на изолированных данных
(XDG), лента — настоящий мост на сервере проверки: к какой сессии пошёл вопрос и
сколько раз создавалась новая — видно по запросам. Живой ответ модели не ждётся —
ключей владельца у проверки нет (docs/TESTING.md, «Чего проверки не видят»).

Предел 180 с: сборка Rust считает минуты, «чинить» по таймауту нельзя
(docs/TESTING.md, «Ловушки стека»).
"""
import sys

from runner_lib import limit, report, run, tool_env, verdict, which

CARGO = [which("cargo"), "test", "--manifest-path", "src-tauri/Cargo.toml", "--test", "session_resume"]
OK = "сессия переживает перезапуск приложения: сохранённый идентификатор берётся из списка живых, списка нет — новая создана и запомнена"


def check():
    code, output = run(CARGO, limit("session_resume"), env=tool_env())
    return verdict(code, output, OK)


if __name__ == "__main__":
    sys.exit(report(check()))
