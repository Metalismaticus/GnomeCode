"""Старый чат открывается кликом из сайдбара (карточка b20261009-p4b-openchats).

Проверка идёт по тому же пути, что и продукт: живой движок на изолированных
данных не нужен — лента настоящий мост на loopback-сервере проверки, история
сессии читается маршрутом ядра (`GET /api/session/{id}/message`, живой замер
v2.0.25 от 2026-10-10). Открытие мимо списка движка — строка-уведомление,
сессия не меняется. Живой ответ модели не ждётся (docs/TESTING.md,
«Чего проверки не видят»).

Предел 300 с: сборка Rust считает минуты, «чинить» по таймауту нельзя
(docs/TESTING.md, «Ловушки стека»).
"""
import sys

from runner_lib import limit, report, run, tool_env, verdict, which

CARGO = [which("cargo"), "test", "--manifest-path", "src-tauri/Cargo.toml", "--test", "chat_open"]
OK = ("старый чат открывается: лента чистится reset, история читается из ядра страницами "
      "курсора (старые сверху, строки инструментов — тем же видом, что живая лента), "
      "сессия переключается и запоминается, новый вопрос уходит в неё без строки "
      "«переподключаюсь», промах мимо списка — уведомление без смены сессии")


def check():
    code, output = run(CARGO, limit("chat_open"), env=tool_env())
    return verdict(code, output, OK)


if __name__ == "__main__":
    sys.exit(report(check()))
