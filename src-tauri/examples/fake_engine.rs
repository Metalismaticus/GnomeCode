//! «Движок, который не отвечает»: процесс жив, HTTP нет — как OpenCode server
//! на холодной машине. Проверка движения старта (`tests/startup_freeze.rs`)
//! копирует этот бинарь под именем `opencode.exe` и подсовывает его мосту через
//! PATH; аргументы движка (`serve --hostname …`) игнорируются — важен только
//! сам факт живого процесса, который ни на какой порт не отвечает.
//!
//! Собирается вместе с проверкой (`cargo test --examples`).

use std::thread;
use std::time::Duration;

fn main() {
    // 60 с: дольше предела ожидания ответа движка (30 с); закрытие своё —
    // сироты-процессы за проверкой не остаются.
    thread::sleep(Duration::from_secs(60));
}
